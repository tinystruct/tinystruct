package org.tinystruct;

import org.junit.jupiter.api.Test;
import org.tinystruct.system.ApplicationManager;
import org.tinystruct.system.ApplicationVersionGenerator;
import org.tinystruct.system.HttpServer;

import java.io.BufferedReader;
import java.io.StringReader;
import java.util.Map;
import java.util.Properties;

import static org.junit.jupiter.api.Assertions.*;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

class ApplicationVersionTest {

    private static class DefaultVersionApp extends AbstractApplication {
        @Override
        public void init() {
        }
    }

    private static class CustomVersionApp extends AbstractApplication {
        @Override
        public void init() {
        }

        @Override
        public String version() {
            return "custom-2.0";
        }
    }

    @Test
    void resolveVersionPrefersGeneratedProperties() {
        Properties versions = new Properties();
        versions.setProperty(DefaultVersionApp.class.getName(), " 42 ");

        assertEquals("42", AbstractApplication.resolveVersion(DefaultVersionApp.class, versions));
    }

    @Test
    void resolveVersionFallsBackToFrameworkVersionWhenMissingOrBlank() {
        Properties versions = new Properties();
        versions.setProperty(DefaultVersionApp.class.getName(), "   ");

        assertEquals(ApplicationManager.VERSION, AbstractApplication.resolveVersion(DefaultVersionApp.class, versions));
        assertEquals(ApplicationManager.VERSION, AbstractApplication.resolveVersion(DefaultVersionApp.class, null));
    }

    @Test
    void subclassCanOmitOrOverrideVersion() {
        DefaultVersionApp defaultApp = new DefaultVersionApp();
        assertNotNull(defaultApp.version());
        assertFalse(defaultApp.version().isBlank());

        CustomVersionApp customApp = new CustomVersionApp();
        assertEquals("custom-2.0", customApp.version());
    }

    @Test
    void parseGitLogCountsCommitsPerJavaClass() throws Exception {
        String gitOutput = """
                src/main/java/org/tinystruct/system/HttpServer.java
                src/main/java/org/tinystruct/system/HttpServer.java
                src/main/java/org/tinystruct/mcp/MCPApplication.java
                src/main/resources/application.properties
                pom.xml

                src/main/java/org/tinystruct/system/HttpServer.java
                """;

        try (BufferedReader reader = new BufferedReader(new StringReader(gitOutput))) {
            Map<String, Integer> counts = ApplicationVersionGenerator.parseGitLog(reader, "src/main/java");
            assertEquals(2, counts.size());
            assertEquals(3, counts.get("org.tinystruct.system.HttpServer"));
            assertEquals(1, counts.get("org.tinystruct.mcp.MCPApplication"));
        }
    }

    @Test
    void parseGitLogCarriesHistoryAcrossRenames() throws Exception {
        // Newest commit first, as git log prints it
        String gitOutput = "M\tsrc/main/java/org/example/NewName.java\n"
                + "\n"
                + "R095\tsrc/main/java/org/example/OldName.java\tsrc/main/java/org/example/NewName.java\n"
                + "\n"
                + "M\tsrc/main/java/org/example/OldName.java\n"
                + "\n"
                + "A\tsrc/main/java/org/example/OldName.java\n";

        try (BufferedReader reader = new BufferedReader(new StringReader(gitOutput))) {
            Map<String, Integer> counts = ApplicationVersionGenerator.parseGitLog(reader, "src/main/java/");
            assertEquals(Map.of("org.example.NewName", 4), counts);
        }
    }

    @Test
    void onlyConcreteAppsUsingInheritedVersionAreListed() throws Exception {
        assertTrue(ApplicationVersionGenerator.usesGeneratedVersion(DefaultVersionApp.class));
        assertFalse(ApplicationVersionGenerator.usesGeneratedVersion(CustomVersionApp.class));
        assertFalse(ApplicationVersionGenerator.usesGeneratedVersion(AbstractApplication.class));
        assertFalse(ApplicationVersionGenerator.usesGeneratedVersion(String.class));
    }

    @Test
    void builtApplicationReceivesAutoGeneratedNumericVersion() {
        // The resource only exists after the Maven exec step runs with full Git history
        // (absent in IDE-only builds, source archives, and shallow clones).
        Properties generated = AbstractApplication.loadApplicationVersions(getClass().getClassLoader());
        assumeTrue(generated.containsKey(HttpServer.class.getName()),
                "Generated " + AbstractApplication.APPLICATION_VERSIONS_RESOURCE + " not available");

        HttpServer server = new HttpServer();
        String version = server.version();
        assertNotNull(version);
        assertTrue(version.matches("\\d+"), "Expected numeric auto-generated version, got: " + version);
        assertTrue(Integer.parseInt(version) > 0);
    }
}
